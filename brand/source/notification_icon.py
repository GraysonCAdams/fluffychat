# Writes the Android notification icon as a vector drawable, drawn from the same geometry as the glyph
# (seam_mark.py), so the status bar draws it sharp at every density.
# The bubble with its stitches cut out, without the needle and thread, is resolved into filled outlines
# with Skia's path operations: the piece below the seam opaque, the piece above it at the glyph's paler
# opacity (seam_mark.A), since the status bar tints the icon by its alpha alone. The outlines are
# scaled to fill the 24 dp icon with a 1 dp margin on its longer side, as the system's own status bar
# icons do.
# Usage: python3 source/notification_icon.py <out.xml>
# Needs python3 with skia-pathops and fonttools (pip install skia-pathops fonttools).
import os,runpy,sys,tempfile
import pathops
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.svgLib.path import parse_path

out=sys.argv[1]
argv=sys.argv; sys.argv=['seam_mark.py',tempfile.mkdtemp()]
G=runpy.run_path(os.path.join(os.path.dirname(os.path.abspath(__file__)),'seam_mark.py'))
sys.argv=argv

def svg_path(d,transform=None):
    p=pathops.Path(); parse_path(d,p.getPen())
    if transform: p=p.transform(*transform)
    return p
def ellipse(cx,cy,rx,ry):
    k=0.5522847498; p=pathops.Path()
    p.moveTo(cx+rx,cy)
    p.cubicTo(cx+rx,cy+k*ry,cx+k*rx,cy+ry,cx,cy+ry)
    p.cubicTo(cx-k*rx,cy+ry,cx-rx,cy+k*ry,cx-rx,cy)
    p.cubicTo(cx-rx,cy-k*ry,cx-k*rx,cy-ry,cx,cy-ry)
    p.cubicTo(cx+k*rx,cy-ry,cx+rx,cy-k*ry,cx+rx,cy)
    p.close(); return p
def stroked(p,width,cap=pathops.LineCap.ROUND_CAP,join=pathops.LineJoin.ROUND_JOIN):
    s=pathops.Path(); s.addPath(p); s.stroke(width,cap,join,4); s.convertConicsToQuads(); return s
def op(a,b,kind): return pathops.op(a,b,kind)
U,D,I=pathops.PathOp.UNION,pathops.PathOp.DIFFERENCE,pathops.PathOp.INTERSECTION

shape=ellipse(G['CX'],G['CY'],G['RX'],G['RY'])
tail=G['TAIL'].split('d="')[1].split('"')[0]
shape=op(shape,svg_path(tail),U)

# the bubble with its four stitches cut out; the needle and thread are left off, which keeps the
# silhouette readable at status-bar size
stitches=pathops.Path()
pts=G['PTS']
for a0,b0 in [(0,2),(4,6),(8,10),(12,14)]:
    line=pathops.Path(); line.moveTo(*pts[a0])
    for x,y in pts[a0+1:b0+1]: line.lineTo(x,y)
    stitches=op(stitches,stroked(line,16),U)
glyph=op(shape,stitches,D)
upper=op(glyph,svg_path(G['PALE']),I); lower=op(glyph,svg_path(G['BELOW']),I)

# fit the glyph's bounds into 22 x 22 dp, centred in the 24 dp icon
x0,y0,x1,y1=glyph.bounds
k=22/max(x1-x0,y1-y0)
T=(k,0,0,k,12-k*(x0+x1)/2,12-k*(y0+y1)/2)
upper,lower=upper.transform(*T),lower.transform(*T)

def f(v): return f'{v:.3f}'.rstrip('0').rstrip('.')
def d(path):
    pen=SVGPathPen(None,ntos=f); path.draw(pen); return pen.getCommands()
open(out,'w',newline='\n').write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by brand/source/notification_icon.py from the Seam glyph; edit that, not this. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:fillColor="#FFFFFFFF"
        android:fillAlpha="{G['A']}"
        android:pathData="{d(upper)}" />
    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="{d(lower)}" />
</vector>
''')
print(f'{out}: glyph {f((x1-x0)*k)} x {f((y1-y0)*k)} dp')
